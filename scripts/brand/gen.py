"""Generate the Utilify logo: an extruded "U" whose right arm ends in a green
level block, lit from the top left.

    python3 scripts/brand/gen.py

writes the app icon source (assets/icons/app/utilify.svg; render it to PNG and
ICNS with `cargo run -p utilify-core --example render_app_icon`) and the bare
mark for dark and light backgrounds (assets/brand/).
"""

import math
from pathlib import Path

D = 40  # extrusion depth, toward the top right
OX, OY = -20, -10  # centre the solid (front + depth) in the tile
X0, X1, X2, X3 = 272, 392, 632, 752  # outer left, inner left, inner right, outer right
TOP, BOWL = 300, 566  # arm tops, and where the arms turn into the bowl
GREEN_H = 120  # height of the green block
R_OUT, R_IN = (X3 - X0) / 2, (X2 - X1) / 2
CX = (X0 + X3) / 2


def u_path():
    return (
        f"M{X0} {TOP} H{X1} V{BOWL} A{R_IN} {R_IN} 0 0 0 {X2} {BOWL} V{TOP} H{X3} "
        f"V{BOWL} A{R_OUT} {R_OUT} 0 0 1 {X0} {BOWL} Z"
    )


def mix(c1, c2, t):
    """Blend two #rrggbb colours."""
    a = [int(c1[i : i + 2], 16) for i in (1, 3, 5)]
    b = [int(c2[i : i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(a, b))


def strip(r, a0, a1, shade, n=48):
    """The extruded side of the bowl's arc of radius r, from angle a0 to a1
    (degrees, clockwise from +x with y down), as thin slices shaded by
    `shade(t)`, t in 0..1. Slices overlap a little so no seams show."""
    out = []
    for i in range(n):
        t0, t1 = i / n, min(1, (i + 1.6) / n)
        pts = []
        for t in (t0, t1):
            ang = math.radians(a0 + (a1 - a0) * t)
            pts.append((CX + r * math.cos(ang), BOWL + r * math.sin(ang)))
        (x0, y0), (x1, y1) = pts
        d = (
            f"M{x0:.1f} {y0:.1f} L{x1:.1f} {y1:.1f} L{x1 + D:.1f} {y1 - D:.1f} "
            f"L{x0 + D:.1f} {y0 - D:.1f} Z"
        )
        out.append(f'<path d="{d}" fill="{shade((t0 + t1) / 2)}"/>')
    return "".join(out)


def side(x, y0, y1, fill):
    """A flat side face: the vertical edge at x from y0 to y1, extruded."""
    return f'<path d="M{x} {y0} L{x + D} {y0 - D} L{x + D} {y1 - D} L{x} {y1} Z" fill="{fill}"/>'


def cap(x0, x1, fill):
    """An arm's top face."""
    return f'<path d="M{x0} {TOP} L{x0 + D} {TOP - D} H{x1 + D} L{x1} {TOP} Z" fill="{fill}"/>'


def mark(on_light=False):
    """The extruded U. Besides the front face, what shows is both arms' top
    caps, the outer right side (the right arm, then the bowl until it turns
    away at 45 degrees) and, through the counter, the left arm's inner side
    and the inner bowl. Faces turned up are lighter, faces turned right or
    down darker."""
    if on_light:
        arm, bowl_end, inner, inner_low, cap_left = "#b4b4b4", "#d4d4d4", "#a4a4a4", "#cdcdcd", "#7a7a7a"
    else:
        arm, bowl_end, inner, inner_low, cap_left = "#7a7a7a", "#474747", "#858585", "#b0b0b0", "#d4d4d4"
    return (
        f'<g transform="translate({OX} {OY})">'
        # Through the counter: the inner bowl from the left (180) round the
        # bottom to where it turns away (45), and the left arm's inner side.
        # The flat faces run a few units past where the bowl starts and are
        # drawn over its strips, so the joins show no antialiasing seam.
        + strip(R_IN, 180, 45, lambda t: mix(inner, inner_low, min(1, t * 1.6)))
        + side(X1, TOP, BOWL + 6, inner)
        # The outer right side: the bowl, then the arm (green under the block).
        + strip(R_OUT, 0, 45, lambda t: mix(arm, bowl_end, t))
        + side(X3, TOP + GREEN_H - 1, BOWL + 6, arm)
        + side(X3, TOP, TOP + GREEN_H, "#23864a")
        + cap(X0, X1, cap_left)
        + cap(X2, X3, "#8ff0b4")
        + f'<path d="{u_path()}" fill="url(#face)"/>'
        + f'<path d="M{X2} {TOP} h{X3 - X2} v{GREEN_H} h{X2 - X3} Z" fill="url(#g)"/>'
        + "</g>"
    )


def defs(on_light=False):
    face = ("#2a2a2a", "#111111") if on_light else ("#ffffff", "#dcdcdc")
    return (
        f'<linearGradient id="face" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{face[0]}"/>'
        f'<stop offset="1" stop-color="{face[1]}"/></linearGradient>'
        '<linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#6fe39c"/>'
        '<stop offset="1" stop-color="#3fc46f"/></linearGradient>'
    )


TILE = (
    '<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#262626"/>'
    '<stop offset="1" stop-color="#0c0c0c"/></linearGradient>'
)


def app_icon():
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">\n'
        '  <!-- Utilify app icon: an extruded "U" whose right arm ends in a green\n'
        "       level block. Generated by scripts/brand/gen.py; the source of\n"
        "       utilify.png and utilify.icns (render_app_icon example). -->\n"
        f"<defs>{defs()}{TILE}</defs>"
        '<rect x="100" y="114" width="824" height="824" rx="185" fill="#000" opacity="0.28"/>'
        '<rect x="100" y="100" width="824" height="824" rx="185" fill="url(#bg)"/>'
        '<rect x="102" y="102" width="820" height="820" rx="183" fill="none" stroke="#ffffff" '
        'stroke-opacity="0.09" stroke-width="4"/>' + mark() + "\n</svg>\n"
    )


def mark_only(on_light=False):
    """The mark alone, cropped to the solid (520 x 546)."""
    x, y = X0 + OX, TOP - D + OY
    w, h = (X3 - X0) + D, BOWL + R_OUT - (TOP - D)
    which = "light" if on_light else "dark"
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w:g}" height="{h:g}" viewBox="{x} {y} {w:g} {h:g}">\n'
        f"  <!-- Utilify mark for {which} backgrounds, without the app tile.\n"
        "       Generated by scripts/brand/gen.py. -->\n"
        f"<defs>{defs(on_light)}</defs>" + mark(on_light) + "\n</svg>\n"
    )


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2]
    (root / "assets/icons/app/utilify.svg").write_text(app_icon())
    (root / "assets/brand").mkdir(exist_ok=True)
    (root / "assets/brand/utilify-mark.svg").write_text(mark_only())
    (root / "assets/brand/utilify-mark-on-light.svg").write_text(mark_only(on_light=True))
